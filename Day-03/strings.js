
// Day 03 - JavaScript Strings

// 1. Strings (text)
console.log('Hello');
console.log("JavaScript");

// 2. Strings and numbers together
console.log('Total: ' + 10);

// 3. Template strings
let name = 'Pooja';
let age = 20;

console.log(`My name is ${name}`);
console.log(`I am ${age} years old`);

// 4. Escape characters
console.log('It\'s a beautiful day');
console.log("Hello\nJavaScript");

// 5. Multi-line strings
let message = `Welcome to
JavaScript learning`;

console.log(message);
